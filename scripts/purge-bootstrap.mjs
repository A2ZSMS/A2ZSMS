// Builds src/app/bootstrap-purged.css: Bootstrap's CSS with only the classes the
// site's source code uses (~228KB -> much smaller, less render-blocking CSS).
// Runs automatically before `npm run dev` and `npm run build` (predev/prebuild),
// so new Bootstrap classes added to components are always included.
import { PurgeCSS } from "purgecss";
import { writeFileSync } from "node:fs";

const [result] = await new PurgeCSS().purge({
  css: ["node_modules/bootstrap/dist/css/bootstrap.min.css"],
  content: ["src/**/*.{js,jsx,ts,tsx,json,css,html}"],
  // Keep anything that matches a token in the source, including "col-md-6", "g-4" etc.
  defaultExtractor: (content) => content.match(/[\w-/:%.]+(?<!:)/g) || [],
  keyframes: true,
  variables: false,
  fontFace: true,
  safelist: {
    // Classes and states Bootstrap's own JavaScript adds at runtime
    standard: [
      "show", "showing", "hiding", "fade", "collapse", "collapsing", "collapsed",
      "active", "disabled", "was-validated", "is-valid", "is-invalid",
      "modal-open", "modal-backdrop", "modal-static", "offcanvas-backdrop",
      "dropdown-menu-end", "dropdown-menu-start", "dropup", "dropend", "dropstart",
      "tooltip", "tooltip-inner", "tooltip-arrow", "popover", "popover-arrow",
      "popover-header", "popover-body", "toast", "carousel-item-next",
      "carousel-item-prev", "carousel-item-start", "carousel-item-end",
      "pointer-event", "accordion-button", "accordion-collapse",
      "html", "body",
    ],
    // Theme colours used in class names built at runtime, e.g. `bg-${item.color}-subtle`
    // or `text-${stat.color}` (the purger cannot see the final class name in source)
    deep: [
      /^(bg|text|btn|btn-outline|border|badge|text-bg|link)-(primary|secondary|success|danger|warning|info|light|dark|white|black|body)(-subtle|-emphasis)?$/,
      /^bs-/, /^modal/, /^offcanvas/, /^dropdown/, /^navbar/, /^accordion/, /^carousel/, /^tooltip/, /^popover/],
    greedy: [/data-bs-/, /data-popper/, /aria-/],
  },
});

writeFileSync(
  "src/app/bootstrap-purged.css",
  "/* Generated by scripts/purge-bootstrap.mjs on every dev/build. Do not edit. */\n" +
    result.css
);
console.log(`bootstrap-purged.css: ${(result.css.length / 1024).toFixed(1)} KB`);
